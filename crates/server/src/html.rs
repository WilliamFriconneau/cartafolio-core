/// Escapes a value for safe inclusion in HTML text or attribute values.
/// The single shared escape used by every page the server renders.
pub(crate) fn escape_html(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}
